def cmd_preset(args):
    if args.action == "list":
        for path in sorted(PRESETS.glob("*.json")):
            spec = json.loads(path.read_text(encoding="utf-8"))
            print(f"{spec['name']}\t{spec.get('label', '')}\t{spec.get('summary', '')}")
    else:
        print(json.dumps(load_preset(args.name), ensure_ascii=False, indent=2))


def parser():
    p = argparse.ArgumentParser(prog="ghp.py", description=__doc__.splitlines()[0])
    sub = p.add_subparsers(dest="cmd", required=True)

    pr = sub.add_parser("preset")
    pr.add_argument("action", choices=["list", "show"])
    pr.add_argument("name", nargs="?")
    pr.set_defaults(func=cmd_preset)

    pj = sub.add_parser("project").add_subparsers(dest="action", required=True)
    c = pj.add_parser("create")
    c.add_argument("--owner", required=True)
    c.add_argument("--spec", required=True, help="preset name or path to an edited spec JSON")
    c.add_argument("--title")
    c.add_argument("--repo")
    c.set_defaults(func=cmd_project_create)
    c = pj.add_parser("copy")
    c.add_argument("--source-owner", required=True)
    c.add_argument("--number", required=True, type=int)
    c.add_argument("--owner", required=True)
    c.add_argument("--title", required=True)
    c.add_argument("--repo")
    c.add_argument("--drafts", action="store_true")
    c.set_defaults(func=cmd_project_copy)
    c = pj.add_parser("fields")
    c.add_argument("--owner", required=True)
    c.add_argument("--number", required=True, type=int)
    c.set_defaults(func=cmd_project_fields)

    pb = sub.add_parser("publish")
    pb.add_argument("--roadmap", required=True)
    pb.add_argument("--owner", required=True)
    pb.add_argument("--repo", required=True)
    pb.add_argument("--number", required=True, type=int)
    pb.add_argument("--mapping", choices=["default", "task-issues", "flat"], default="default")
    pb.add_argument("--stories", choices=["body", "issues"], default="body",
                    help="user stories in the feature body (default) or as sub-issues of the feature")
    pb.add_argument("--no-labels", action="store_true")
    pb.add_argument("--no-milestones", action="store_true")
    pb.add_argument("--spec")
    pb.add_argument("--map")
    pb.add_argument("--dry-run", action="store_true")
    pb.set_defaults(func=cmd_publish)

    lk = sub.add_parser("link")
    lk.add_argument("action", choices=["sub", "unsub", "block", "unblock"])
    lk.add_argument("--repo", required=True)
    lk.add_argument("--parent", type=int)
    lk.add_argument("--child", type=int)
    lk.add_argument("--issue", type=int)
    lk.add_argument("--blocker", type=int)
