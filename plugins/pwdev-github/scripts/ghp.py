def load_preset(name_or_path):
    path = Path(name_or_path)
    if not path.is_file():
        path = PRESETS / f"{name_or_path}.json"
    return json.loads(path.read_text(encoding="utf-8"))


def iteration_config(conf, today=None):
    today = today or dt.date.today()
    start = conf.get("start", "next-monday")
    if start == "next-monday":
        start_date = today + dt.timedelta(days=(7 - today.weekday()) % 7 or 7)
    elif start == "today":
        start_date = today
    else:
        start_date = dt.date.fromisoformat(start)
    duration = int(conf.get("duration", 14))
    title = conf.get("title", "Sprint {n}")
    iterations = [
        {"title": title.format(n=i + 1),
         "startDate": (start_date + dt.timedelta(days=i * duration)).isoformat(),
         "duration": duration}
        for i in range(int(conf.get("count", 6)))
    ]
    return {"startDate": start_date.isoformat(), "duration": duration, "iterations": iterations}


def select_options(field):
    return [{"name": o["name"], "color": o.get("color", "GRAY"), "description": o.get("description", "")}
            for o in field.get("options", [])]


PROJECT_QUERY = """
  projectV2(number: $n) {
    id url title
    fields(first: 100) { nodes {
      ... on ProjectV2FieldCommon { id name dataType }
      ... on ProjectV2SingleSelectField { options { id name } }
      ... on ProjectV2IterationField { configuration { iterations { id title startDate } } }
    } }
  }"""


def project_info(owner, number):
    """Project id, url and fields with their data type (field-list does not expose it)."""
    if owner == "@me":
        data = graphql("query($n:Int!){ viewer {" + PROJECT_QUERY + "} }", n=number)
        project = data["viewer"]["projectV2"]
    else:
        data = graphql("query($login:String!,$n:Int!){ repositoryOwner(login:$login) {"
                       " ... on ProjectV2Owner {" + PROJECT_QUERY + "} } }", login=owner, n=number)
        project = (data.get("repositoryOwner") or {}).get("projectV2")
    if not project:
        raise GhError(f"project {owner}/{number} not found (needs the 'project' scope: gh auth refresh -s project)")
    fields = []
    for node in project["fields"]["nodes"]:
        if not node.get("id"):
            continue
        field = {"id": node["id"], "name": node["name"], "dataType": node.get("dataType", "")}
        if node.get("options") is not None:
            field["options"] = node["options"]
        if node.get("configuration"):
            field["iterations"] = node["configuration"]["iterations"]
        fields.append(field)
    return {"id": project["id"], "url": project["url"], "title": project["title"], "fields": fields}


def project_fields(owner, number):
    return project_info(owner, number)["fields"]


def cmd_project_create(args):
    spec = load_preset(args.spec)
    title = args.title or spec.get("title") or spec.get("label") or spec["name"]
    created = gh_json(["project", "create", "--owner", args.owner, "--title", title, "--format", "json"])
    number, project_id, url = created["number"], created["id"], created["url"]
    edit = ["project", "edit", str(number), "--owner", args.owner]
    if spec.get("description"):
        edit += ["--description", spec["description"]]
    if spec.get("readme"):
        edit += ["--readme", spec["readme"]]
    if spec.get("visibility"):
        edit += ["--visibility", spec["visibility"].upper()]
    if len(edit) > 5:
        gh(edit)
    existing = {f["name"]: f for f in project_fields(args.owner, number)}
    report = []
    for field in spec.get("fields", []):
        name, ftype = field["name"], field["type"].upper()
        if field.get("builtin") or name in existing:
            current = existing.get(name)
            if current and ftype == "SINGLE_SELECT":
                graphql(
                    "mutation($id:ID!,$opts:[ProjectV2SingleSelectFieldOptionInput!]){"
                    "updateProjectV2Field(input:{fieldId:$id,singleSelectOptions:$opts}){clientMutationId}}",
                    id=current["id"], opts=select_options(field))
                report.append(f"updated {name}")
            else:
                report.append(f"kept {name}")
            continue
        if ftype == "ITERATION":
            graphql(
                "mutation($p:ID!,$n:String!,$c:ProjectV2IterationFieldConfigurationInput!){"
                "createProjectV2Field(input:{projectId:$p,dataType:ITERATION,name:$n,iterationConfiguration:$c})"
                "{clientMutationId}}",
                p=project_id, n=name, c=iteration_config(field.get("iteration", {})))
        elif ftype == "SINGLE_SELECT":
            graphql(
                "mutation($p:ID!,$n:String!,$o:[ProjectV2SingleSelectFieldOptionInput!]){"
                "createProjectV2Field(input:{projectId:$p,dataType:SINGLE_SELECT,name:$n,singleSelectOptions:$o})"
                "{clientMutationId}}",
                p=project_id, n=name, o=select_options(field))
        else:
            gh(["project", "field-create", str(number), "--owner", args.owner,
                "--name", name, "--data-type", ftype])
        report.append(f"created {name}")
    if args.repo:
        gh(["project", "link", str(number), "--owner", args.owner, "--repo", args.repo])
        report.append(f"linked {args.repo}")
    print(json.dumps({"number": number, "id": project_id, "url": url, "owner": args.owner,
                      "spec": spec["name"], "fields": report,
                      "views": spec.get("views", [])}, ensure_ascii=False, indent=2))


