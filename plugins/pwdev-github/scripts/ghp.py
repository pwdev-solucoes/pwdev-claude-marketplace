# ---------------------------------------------------------------- gh runner

def gh(args, stdin=None):
    try:
        feed = {"input": stdin} if stdin is not None else {"stdin": subprocess.DEVNULL}
        proc = subprocess.run(["gh", *args], capture_output=True, text=True, **feed)
    except FileNotFoundError as exc:
        raise GhError("gh not found — install https://cli.github.com/") from exc
    if proc.returncode != 0:
        raise GhError(f"gh {' '.join(args[:3])}: {proc.stderr.strip() or proc.stdout.strip()}")
    return proc.stdout


def gh_json(args, stdin=None):
    out = gh(args, stdin)
    return json.loads(out) if out.strip() else None


def graphql(query, **variables):
    payload = json.dumps({"query": query, "variables": variables})
    data = gh_json(["api", "graphql", "--input", "-"], stdin=payload)
    if data and data.get("errors"):
        raise GhError("graphql: " + "; ".join(e.get("message", "") for e in data["errors"]))
    return (data or {}).get("data")


def rest(method, path, body=None):
    args = ["api", path, "--method", method, "-H", "Accept: application/vnd.github+json"]
    if body is not None:
        args += ["--input", "-"]
    return gh_json(args, stdin=json.dumps(body) if body is not None else None)


