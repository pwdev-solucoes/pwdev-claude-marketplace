def save_map(path, state):
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(".tmp")
    tmp.write_text(json.dumps(state, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    tmp.replace(path)


def field_setter(fields, spec):
    """role -> (field, {value -> option id}) resolved from the spec, then aliases."""
    by_name = {f["name"]: f for f in fields}
    resolved = {}
    spec_fields = {f.get("role"): f for f in (spec or {}).get("fields", []) if f.get("role")}
    for role, aliases in ROLE_ALIASES.items():
        names = ([spec_fields[role]["name"]] if role in spec_fields else []) + aliases
        field = next((by_name[n] for n in names if n in by_name), None)
        if not field:
            continue
        options = {}
        if field.get("dataType") == "SINGLE_SELECT":
            opt_by_name = {o["name"]: o["id"] for o in field["options"]}
            spec_values = {o.get("value"): o["name"] for o in spec_fields.get(role, {}).get("options", [])}
            for value in set(VALUE_ALIASES) | set(spec_values):
                for candidate in [spec_values.get(value)] + VALUE_ALIASES.get(value, []):
                    if candidate in opt_by_name:
                        options[value] = opt_by_name[candidate]
                        break
        resolved[role] = (field, options)
    return resolved


def set_field(project_id, item_id, field, options, value):
    base = ["project", "item-edit", "--id", item_id, "--project-id", project_id, "--field-id", field["id"]]
    kind = field.get("dataType", "TEXT")
    if kind == "SINGLE_SELECT":
        option = options.get(value) or next((o["id"] for o in field.get("options", []) if o["name"] == value), None)
        if not option:
            return False
        gh(base + ["--single-select-option-id", option])
    elif kind == "ITERATION":
        iteration = next((i["id"] for i in field.get("iterations", []) if i["title"] == value), None)
        if not iteration:
            return False
        gh(base + ["--iteration-id", iteration])
    elif kind == "NUMBER":
        gh(base + ["--number", str(value)])
    elif kind == "DATE":
        gh(base + ["--date", str(value)])
    elif kind == "TEXT":
        gh(base + ["--text", str(value)])
    else:
        return False  # built-in fields (Assignees, Labels, Milestone...) are not item-edit targets
    return True


def ensure_labels(repo, labels):
    existing = set(json.loads(gh(["label", "list", "--repo", repo, "--limit", "500", "--json", "name",
                                  "-q", "[.[].name]"]) or "[]"))
    colors = {"type:epic": "5319E7", "type:feature": "1D76DB", "type:task": "BFD4F2", "type:story": "0E8A16", "status:draft": "EDEDED",
              "priority:must": "B60205", "priority:should": "D93F0B", "priority:could": "FBCA04",
              "priority:wont": "CCCCCC"}
    created = []
    for label in labels:
        if label not in existing:
            gh(["label", "create", label, "--repo", repo, "--color", colors.get(label, "0E8A16")])
            created.append(label)
    return created


def ensure_milestones(repo, plan, state):
    if not plan["milestones"]:
        return
    existing = {m["title"]: m["number"] for m in
                (gh_json(["api", f"repos/{repo}/milestones?state=all&per_page=100"]) or [])}
    for pid, title in plan["milestones"].items():
        if pid in state["milestones"]:
            continue
        number = existing.get(title) or rest("POST", f"repos/{repo}/milestones", {"title": title})["number"]
        state["milestones"][pid] = {"number": number, "title": title}


def cmd_publish(args):
    roadmap_path = Path(args.roadmap)
    roadmap = json.loads(roadmap_path.read_text(encoding="utf-8"))
    plan = build_plan(roadmap, roadmap_path, args.mapping, not args.no_labels, not args.no_milestones,
                      args.stories)
    map_path = Path(args.map or f".planning/github/{plan['slug']}.map.json")
    state = load_map(map_path, args.repo, args.owner, args.number)
    diff = diff_plan(plan, state)
    if args.dry_run:
        print(json.dumps({"dry_run": True, "repo": args.repo, "project": args.number,
                          "mapping": args.mapping, "stories": args.stories, "map": str(map_path), **diff},
                         ensure_ascii=False, indent=2))
        return 0
    spec = load_preset(args.spec) if args.spec else None
    log = []
    try:
        project = project_info(args.owner, args.number)
        state["project_number"], state["project_url"] = args.number, project["url"]
        project_id = project["id"]
        setters = field_setter(project["fields"], spec)
        if plan["labels"]:
            created = ensure_labels(args.repo, plan["labels"])
            if created:
                log.append(f"labels created: {', '.join(created)}")
        ensure_milestones(args.repo, plan, state)
        save_map(map_path, state)
        for issue in plan["issues"]:
            payload = {"title": issue["title"], "body": issue["body"], "labels": issue["labels"]}
            if issue["milestone"]:
                payload["milestone"] = state["milestones"][issue["phase_id"]]["number"]
            entry = state["issues"].get(issue["id"])
            digest = issue_hash(issue)
            if not entry:
                made = rest("POST", f"repos/{args.repo}/issues", payload)
                entry = {"number": made["number"], "id": made["id"], "node_id": made["node_id"],
                         "url": made["html_url"], "hash": digest}
                state["issues"][issue["id"]] = entry
                log.append(f"created #{made['number']} {issue['id']}")
            elif entry.get("hash") != digest:
                rest("PATCH", f"repos/{args.repo}/issues/{entry['number']}", payload)
                entry["hash"] = digest
                log.append(f"updated #{entry['number']} {issue['id']}")
            save_map(map_path, state)
            if not entry.get("item_id"):
                item = gh_json(["project", "item-add", str(args.number), "--owner", args.owner,
                                "--url", entry["url"], "--format", "json"])
                entry["item_id"] = item["id"]
                if "status" in setters:
                    set_field(project_id, entry["item_id"], *setters["status"], "backlog")
                save_map(map_path, state)
            for role, value in issue["fields"].items():
                if value in (None, "") or role not in setters:
                    continue
                if entry.get("fields", {}).get(role) == value:
                    continue
                if set_field(project_id, entry["item_id"], *setters[role], value):
                    entry.setdefault("fields", {})[role] = value
            save_map(map_path, state)
        for parent, child in plan["sub_issues"]:
            key = f"{parent}>{child}"
            if key in state["sub_issues"]:
                continue
            rest("POST", f"repos/{args.repo}/issues/{state['issues'][parent]['number']}/sub_issues",
                 {"sub_issue_id": state["issues"][child]["id"]})
            state["sub_issues"].append(key)
            save_map(map_path, state)
        t = TEXT[lang_of(roadmap)]
        for blocked, blocker in plan["blocked_by"]:
            key = f"{blocked}>{blocker}"
            if key in state["blocked_by"] or key in state.get("fallback_blocked_by", []):
                continue
            target = state["issues"][blocked]["number"]
            source = state["issues"][blocker]
            try:
                rest("POST", f"repos/{args.repo}/issues/{target}/dependencies/blocked_by",
                     {"issue_id": source["id"]})
                state["blocked_by"].append(key)
            except GhError as exc:
                if not re.search(r"\b(404|410|422)\b|Not Found", str(exc)):
                    raise
                gh(["issue", "comment", str(target), "--repo", args.repo, "--body",
                    t["blocked_fallback"].format(number=source["number"], id=blocker)])
                state.setdefault("fallback_blocked_by", []).append(key)
                log.append(f"blocked-by fallback comment on #{target}")
            save_map(map_path, state)
    except GhError as exc:
        save_map(map_path, state)
        print(json.dumps({"status": "FAILED", "error": str(exc), "map": str(map_path),
                          "done": log, "resume": "run the same publish again; finished steps are skipped"},
                         ensure_ascii=False, indent=2))
        return 1
    print(json.dumps({"status": "OK", "project_url": state["project_url"], "map": str(map_path),
                      "issues": len(state["issues"]), "sub_issues": len(state["sub_issues"]),
                      "blocked_by": len(state["blocked_by"]),
                      "fallback_blocked_by": len(state.get("fallback_blocked_by", [])),
                      "milestones": len(state["milestones"]), "log": log}, ensure_ascii=False, indent=2))
    return 0


# ---------------------------------------------------------------- single-issue helpers

def issue_ref(repo, number):
    return gh_json(["api", f"repos/{repo}/issues/{number}"])


def cmd_link(args):
    if args.action in ("sub", "unsub"):
        child = issue_ref(args.repo, args.child)
        if args.action == "sub":
            rest("POST", f"repos/{args.repo}/issues/{args.parent}/sub_issues", {"sub_issue_id": child["id"]})
        else:
            rest("DELETE", f"repos/{args.repo}/issues/{args.parent}/sub_issue", {"sub_issue_id": child["id"]})
        print(f"{args.action} #{args.child} under #{args.parent}: ok")
    else:
        blocker = issue_ref(args.repo, args.blocker)
        if args.action == "block":
            rest("POST", f"repos/{args.repo}/issues/{args.issue}/dependencies/blocked_by",
                 {"issue_id": blocker["id"]})
        else:
            rest("DELETE", f"repos/{args.repo}/issues/{args.issue}/dependencies/blocked_by/{blocker['id']}")
        print(f"{args.action} #{args.issue} by #{args.blocker}: ok")


def cmd_deps(args):
    def brief(items):
        return [{"number": i["number"], "title": i["title"], "state": i["state"]} for i in items or []]
    out = {
        "issue": args.issue,
        "blocked_by": brief(gh_json(["api", f"repos/{args.repo}/issues/{args.issue}/dependencies/blocked_by"])),
        "blocking": brief(gh_json(["api", f"repos/{args.repo}/issues/{args.issue}/dependencies/blocking"])),
        "sub_issues": brief(gh_json(["api", f"repos/{args.repo}/issues/{args.issue}/sub_issues"])),
    }
    print(json.dumps(out, ensure_ascii=False, indent=2))


def cmd_item_set(args):
    project = project_info(args.owner, args.number)
    fields = {f["name"]: f for f in project["fields"]}
    if args.field not in fields:
        raise GhError(f"field {args.field!r} not in project; available: {', '.join(sorted(fields))}")
    item = gh_json(["project", "item-add", str(args.number), "--owner", args.owner, "--url", args.url,
                    "--format", "json"])  # returns the existing item when already added
    if not set_field(project["id"], item["id"], fields[args.field], {}, args.value):
        field = fields[args.field]
        options = ", ".join(o.get("name") or o.get("title") for o in field.get("options") or field.get("iterations") or [])
        raise GhError(f"value {args.value!r} not an option of {args.field}: {options}")
    print(f"{args.field} = {args.value}: ok")


