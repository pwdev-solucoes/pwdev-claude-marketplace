# ---------------------------------------------------------------- roadmap planning (pure)

def feature_of(nid):
    return re.sub(r"-T\d{2}$", "", nid)


def waves(nodes, edges):
    features = sorted(n["id"] for n in nodes if n["type"] == "feature")
    preds = {f: set() for f in features}
    for e in edges:
        a, b = feature_of(e["from"]), feature_of(e["to"])
        if a != b and a in preds and b in preds:
            preds[b].add(a)
    level = {}

    def lv(f, seen=()):
        if f in seen:
            raise ValueError(f"dependency cycle through {f}")
        if f not in level:
            level[f] = 1 + max((lv(p, seen + (f,)) for p in preds[f]), default=0)
        return level[f]

    for f in features:
        lv(f)
    return level


def lang_of(roadmap):
    lang = (roadmap.get("meta") or {}).get("language", "en")
    return "pt-BR" if lang.lower().startswith("pt") else "en"


def issue_nodes(roadmap, mapping):
    types = {"default": {"epic", "feature"}, "task-issues": {"epic", "feature", "task"},
             "flat": {"feature"}}[mapping]
    return [n for n in roadmap["nodes"] if n["type"] in types]


def story_block(story, roadmap, t, heading):
    """Story line, CA checklist and the business rules it applies, as Markdown."""
    rules = {r["id"]: r for r in roadmap.get("rules") or []}
    lines = []
    if heading:
        draft = f" _({t['draft']})_" if story.get("status") != "ready" else ""
        lines += [f"#### {story['id']} — {story['title']}{draft}", ""]
    lines.append(t["story_line"].format(persona=story.get("persona", ""), action=story.get("action", ""),
                                        value=story.get("value", "")))
    lines += ["", f"**{t['acceptance']}:**", ""]
    for ca in story.get("acceptance") or []:
        tag = f"{ca['id']} ({ca.get('path', '')}" + (f", {', '.join(ca['rules'])}" if ca.get("rules") else "") + ")"
        if ca.get("type") == "gherkin":
            lines += [f"- [ ] **{tag}**", "", "  ```gherkin"] + [f"  {l}" for l in ca.get("text", "").splitlines()] + ["  ```"]
        else:
            lines.append(f"- [ ] **{tag}** {ca.get('text', '')}")
    if story.get("rules"):
        lines += ["", f"**{t['rules']}:**", ""]
        for rid in story["rules"]:
            rule = rules.get(rid, {})
            example = f" _{t['example']} {rule['example']}_" if rule.get("example") else ""
            lines.append(f"- **{rid} — {rule.get('title', '')}:** {rule.get('rule', '')}{example}")
    if story.get("out_of_scope"):
        lines += ["", f"**{t['out_of_scope']}:** {story['out_of_scope']}"]
    return lines


def render_story_body(story, roadmap, roadmap_path, by_id):
    t = TEXT[lang_of(roadmap)]
    feature = by_id.get(story["feature"], {})
    lines = [t["story_intro"].format(feature=f"{story['feature']} {feature.get('title', '')}".strip()), ""]
    meta = [f"**{t['priority']}:** {story.get('priority', '')}", f"**Status:** {story.get('status', '')}"]
    if story.get("depends_on"):
        meta.append(f"**{t['depends']}:** {', '.join(story['depends_on'])}")
    lines += [" · ".join(meta), ""] + story_block(story, roadmap, t, heading=False)
    lines += ["", "---", "", "_" + t["generated"].format(roadmap=os.path.relpath(roadmap_path), id=story["id"]) + "_"]
    return "\n".join(lines) + "\n"


def render_body(node, roadmap, roadmap_path, by_id, children, wave_of, mapping, stories_mode="body"):
    t = TEXT[lang_of(roadmap)]
    title = (roadmap.get("meta") or {}).get("title", "")
    lines = []
    kind = node["type"]
    if kind == "epic":
        lines.append(t["epic_intro"].format(title=title))
    elif kind == "feature":
        lines.append(t["feature_intro"].format(title=title))
    else:
        lines.append(t["task_intro"].format(parent=node["parent"]))
    lines.append("")
    phase = node["id"][:3]
    meta = [f"**{t['phase']}:** {phase} {by_id.get(phase, {}).get('title', '')}".rstrip()]
    if kind == "feature":
        meta += [f"**{t['priority']}:** {node.get('priority', '')}",
                 f"**{t['estimate']}:** {node.get('estimate', '')}",
                 f"**{t['wave']}:** {wave_of.get(node['id'], '')}"]
        if node.get("requirements"):
            meta.append(f"**{t['requirements']}:** {', '.join(node['requirements'])}")
    lines.append(" · ".join(meta))
    deps = sorted({e["from"] for e in roadmap.get("edges", []) if e["to"] == node["id"]})
    if deps:
        lines += ["", f"**{t['depends']}:** " + ", ".join(f"{d} {by_id[d]['title']}" for d in deps if d in by_id)]
    if node.get("acceptance"):
        lines += ["", f"### {t['acceptance']}", ""] + [f"- [ ] {a}" for a in node["acceptance"]]
    kids = children.get(node["id"], [])
    if kind == "feature" and kids and mapping != "task-issues":
        lines += ["", f"### {t['tasks']}", ""] + [f"- [ ] {k} {by_id[k]['title']}" for k in kids]
    if kind == "epic" and mapping == "flat":
        lines += ["", f"### {t['features']}", ""] + [f"- {k} {by_id[k]['title']}" for k in kids]
    stories = [s for s in roadmap.get("stories") or [] if s.get("feature") == node["id"]]
    if kind == "feature" and stories:
        lines += ["", f"### {t['stories']}", ""]
        if stories_mode == "issues":
            lines += [f"- {s['id']} {s['title']}" + (f" _({t['draft']})_" if s.get("status") != "ready" else "")
                      for s in stories]
        else:
            for s in stories:
                lines += story_block(s, roadmap, t, heading=True) + [""]
    rel = node.get("path")
    if rel:
        src = (Path(roadmap_path).parent / rel)
        lines += ["", f"**{t['source']}:** `{os.path.relpath(src)}`"]
        if kind != "task" and src.is_file():
            content = src.read_text(encoding="utf-8")
            lines += ["", f"<details><summary>{t['details']}</summary>", "", content.strip(), "", "</details>"]
    lines += ["", "---", "", "_" + t["generated"].format(roadmap=os.path.relpath(roadmap_path), id=node["id"]) + "_"]
    body = "\n".join(lines) + "\n"
    if len(body) > BODY_LIMIT:
        cut = body.find("<details>")
        body = body[:cut] + "_" + t["generated"].format(roadmap=os.path.relpath(roadmap_path), id=node["id"]) + "_\n"
    return body


def labels_for(node, slug, mapping):
    labels = [f"type:{node['type']}", f"prd:{slug}"]
    if node.get("priority"):
        labels.append(f"priority:{node['priority']}")
    return labels


def build_plan(roadmap, roadmap_path, mapping="default", use_labels=True, use_milestones=True,
               stories_mode="body"):
    """Everything publish will do, derived from the roadmap alone (no gh calls)."""
    if roadmap.get("schema") != ROADMAP_SCHEMA:
        raise ValueError(f"roadmap schema must be {ROADMAP_SCHEMA}")
    slug = (roadmap.get("meta") or {}).get("slug", "roadmap")
    by_id = {n["id"]: n for n in roadmap["nodes"]}
    children = {}
    for n in roadmap["nodes"]:
        if n.get("parent"):
            children.setdefault(n["parent"], []).append(n["id"])
    for k in children:
        children[k].sort()
    wave_of = waves(roadmap["nodes"], roadmap.get("edges", []))
    as_issue = {n["id"] for n in issue_nodes(roadmap, mapping)}
    milestones = {}
    if use_milestones:
        for n in roadmap["nodes"]:
            if n["type"] == "phase":
                milestones[n["id"]] = f"{n['id']} {n['title']}"
    issues = []
    for n in sorted(issue_nodes(roadmap, mapping), key=lambda x: x["id"]):
        issues.append({
            "id": n["id"],
            "type": n["type"],
            "title": f"[{n['id']}] {n['title']}",
            "body": render_body(n, roadmap, roadmap_path, by_id, children, wave_of, mapping, stories_mode),
            "labels": labels_for(n, slug, mapping) if use_labels else [],
            "milestone": milestones.get(n["id"][:3]),
            "phase_id": n["id"][:3],
            "fields": {
                "type": n["type"],
                "priority": n.get("priority") or by_id.get(n.get("parent") or "", {}).get("priority"),
                "estimate": n.get("estimate"),
                "phase": f"{n['id'][:3]} {by_id.get(n['id'][:3], {}).get('title', '')}".strip(),
                "wave": wave_of.get(feature_of(n["id"])) if n["type"] != "epic" else None,
                "requirements": ", ".join(n.get("requirements") or []) or None,
            },
        })
    if stories_mode == "issues":
        for s in sorted(roadmap.get("stories") or [], key=lambda x: x["id"]):
            fid = s["feature"]
            labels = ["type:story", f"prd:{slug}"] + ([f"priority:{s['priority']}"] if s.get("priority") else [])
            if s.get("status") != "ready":
                labels.append("status:draft")
            issues.append({
                "id": s["id"], "type": "story",
                "title": f"[{s['id']}] {s['title']}",
                "body": render_story_body(s, roadmap, roadmap_path, by_id),
                "labels": labels if use_labels else [],
                "milestone": milestones.get(fid[:3]),
                "phase_id": fid[:3],
                "fields": {"type": "story", "priority": s.get("priority"),
                           "phase": f"{fid[:3]} {by_id.get(fid[:3], {}).get('title', '')}".strip(),
                           "wave": wave_of.get(fid),
                           "requirements": ", ".join(s.get("rules") or []) or None},
            })
            as_issue.add(s["id"])
    sub_issues = []
    if stories_mode == "issues":
        sub_issues += [(s["feature"], s["id"]) for s in roadmap.get("stories") or [] if s["feature"] in as_issue]
    if mapping != "flat":
        for iid in sorted(as_issue):
            parent = by_id.get(iid, {}).get("parent")
            if parent in as_issue:
                sub_issues.append((parent, iid))
    blocked = set()
    for e in roadmap.get("edges", []):
        a, b = e["from"], e["to"]
        if a not in as_issue:
            a = feature_of(a)
        if b not in as_issue:
            b = feature_of(b)
        if a != b and a in as_issue and b in as_issue:
            blocked.add((b, a))  # b is blocked by a
    if stories_mode == "issues":
        for s in roadmap.get("stories") or []:
            for dep in s.get("depends_on") or []:
                if dep in as_issue:
                    blocked.add((s["id"], dep))
    labels = sorted({label for i in issues for label in i["labels"]})
    return {"slug": slug, "mapping": mapping, "stories": stories_mode, "milestones": milestones, "issues": issues,
            "sub_issues": sorted(sub_issues), "blocked_by": sorted(blocked), "labels": labels}


def issue_hash(issue):
    raw = json.dumps({k: issue[k] for k in ("title", "body", "labels", "milestone")}, sort_keys=True)
    return hashlib.sha256(raw.encode()).hexdigest()[:16]


def load_map(path, repo, owner, number):
    if path.is_file():
        data = json.loads(path.read_text(encoding="utf-8"))
        if data.get("repo") != repo:
            raise ValueError(f"map {path} belongs to {data.get('repo')}, not {repo}")
        return data
    return {"schema": MAP_SCHEMA, "repo": repo, "owner": owner, "project_number": number,
            "project_url": None, "milestones": {}, "issues": {}, "sub_issues": [], "blocked_by": [],
            "fallback_blocked_by": []}


def diff_plan(plan, state):
    creates = [i["id"] for i in plan["issues"] if i["id"] not in state["issues"]]
    updates = [i["id"] for i in plan["issues"]
               if i["id"] in state["issues"] and state["issues"][i["id"]].get("hash") != issue_hash(i)]
    done_links = set(state["sub_issues"])
    done_blocks = set(state["blocked_by"]) | set(state.get("fallback_blocked_by", []))
    subs = [f"{p}>{c}" for p, c in plan["sub_issues"] if f"{p}>{c}" not in done_links]
    blocks = [f"{b}>{a}" for b, a in plan["blocked_by"] if f"{b}>{a}" not in done_blocks]
    miles = [k for k in plan["milestones"] if k not in state["milestones"]]
    items = [i["id"] for i in plan["issues"] if not state["issues"].get(i["id"], {}).get("item_id")]
    return {"create": creates, "update": updates, "unchanged": len(plan["issues"]) - len(creates) - len(updates),
            "milestones": miles, "sub_issues": subs, "blocked_by": blocks, "project_items": items,
            "labels": plan["labels"],
            "orphans": sorted(set(state["issues"]) - {i["id"] for i in plan["issues"]})}


