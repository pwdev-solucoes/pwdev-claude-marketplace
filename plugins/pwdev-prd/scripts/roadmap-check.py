#!/usr/bin/env python3
"""roadmap-check.py — deterministic validator for a pwdev-roadmap/1 roadmap.json.

Validates the hierarchy, IDs, traceability, and the dependency graph, then
computes waves (topological levels of features that can run in parallel) and
the critical path, and renders DEPENDENCIES.md next to roadmap.json.

Usage:
  roadmap-check.py <roadmap.json> [--no-write] [--json]

Exit code 0 on PASS, 1 on FAIL, 2 on unreadable input. Standard library only.
"""
