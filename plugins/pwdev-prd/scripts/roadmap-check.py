def load(path: Path):
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        print(f"FAIL\n- cannot read {path}: {exc}")
        sys.exit(2)


def find_cycle(nodes, succ):
    """Return one cycle as a list of ids, or None."""
    state = {n: 0 for n in nodes}  # 0 new, 1 on stack, 2 done
    stack = []

    def visit(n):
        state[n] = 1
        stack.append(n)
        for m in succ.get(n, ()):
            if state.get(m) == 1:
                return stack[stack.index(m):] + [m]
            if state.get(m) == 0:
                found = visit(m)
                if found:
                    return found
        stack.pop()
        state[n] = 2
        return None

    for n in sorted(nodes):
        if state[n] == 0:
            found = visit(n)
            if found:
                return found
    return None


def validate(data, root: Path, check_files=True):
    errors, warnings = [], []
    if data.get("schema") != SCHEMA:
        errors.append(f"schema must be '{SCHEMA}' (got {data.get('schema')!r})")
    nodes = data.get("nodes")
    if not isinstance(nodes, list) or not nodes:
        errors.append("nodes must be a non-empty list")
        return errors, warnings, {}
    requirements = data.get("requirements") or []
    if not requirements:
        errors.append("requirements must list the PRD requirement IDs (FR-xx, NFR-xx)")

    by_id = {}
    for i, node in enumerate(nodes):
        nid, ntype = node.get("id"), node.get("type")
        if not nid or ntype not in ID_PATTERNS:
            errors.append(f"nodes[{i}]: needs id and a type in {sorted(ID_PATTERNS)}")
            continue
        if nid in by_id:
            errors.append(f"{nid}: duplicate id")
            continue
        by_id[nid] = node
        if not ID_PATTERNS[ntype].match(nid):
            errors.append(f"{nid}: id does not match the {ntype} pattern")
        if not node.get("title"):
            errors.append(f"{nid}: missing title")
        if check_files:
            rel = node.get("path")
            if not rel:
                errors.append(f"{nid}: missing path")
            elif not (root / rel).is_file():
                errors.append(f"{nid}: path not found: {rel}")

    children = {nid: [] for nid in by_id}
    for nid, node in by_id.items():
        expected = PARENT_TYPE[node["type"]]
        parent = node.get("parent")
        if expected is None:
            if parent:
                errors.append(f"{nid}: a phase has no parent")
            continue
        if parent not in by_id:
            errors.append(f"{nid}: parent {parent!r} not found")
        elif by_id[parent]["type"] != expected:
            errors.append(f"{nid}: parent {parent} must be a {expected}")
        elif not nid.startswith(parent + "-"):
            errors.append(f"{nid}: id must extend its parent id {parent}")
        else:
            children[parent].append(nid)

    features = [n for n, v in by_id.items() if v["type"] == "feature"]
    covered = set()
    for fid in features:
        node = by_id[fid]
        if not node.get("acceptance"):
            errors.append(f"{fid}: feature without acceptance criteria")
        reqs = node.get("requirements") or []
        if not reqs:
            errors.append(f"{fid}: feature without origin requirement")
        for req in reqs:
            if req not in requirements:
                errors.append(f"{fid}: requirement {req} is not in the PRD requirement list")
            covered.add(req)
        if node.get("priority") not in PRIORITIES:
            errors.append(f"{fid}: priority must be one of {sorted(PRIORITIES)}")
        if node.get("estimate") not in ESTIMATES:
            errors.append(f"{fid}: estimate must be one of {sorted(ESTIMATES)}")
        if len(children[fid]) > MAX_TASKS_PER_FEATURE:
            errors.append(f"{fid}: {len(children[fid])} tasks, split the feature (max {MAX_TASKS_PER_FEATURE})")
    for req in requirements:
        if req.startswith("FR-") and req not in covered:
            errors.append(f"{req}: functional requirement with no feature")
        elif req not in covered:
            warnings.append(f"{req}: requirement with no feature")
    for eid, node in by_id.items():
        if node["type"] == "epic":
            if not children[eid]:
                errors.append(f"{eid}: epic without features")
            elif len(children[eid]) > MAX_FEATURES_PER_EPIC:
                errors.append(f"{eid}: {len(children[eid])} features, split the epic (max {MAX_FEATURES_PER_EPIC})")
        if node["type"] == "phase" and not children[eid]:
            errors.append(f"{eid}: phase without epics")
    if len(features) > MAX_FEATURES:
        errors.append(f"{len(features)} features: split the product into modules first (max {MAX_FEATURES})")

    # Dependency graph: edge {from: A, to: B} means B depends on A (A blocks B).
    succ, seen = {}, set()
    edges = data.get("edges") or []
    for i, edge in enumerate(edges):
        a, b, kind = edge.get("from"), edge.get("to"), edge.get("kind")
        label = f"edges[{i}] {a}->{b}"
        if a not in by_id or b not in by_id:
            errors.append(f"{label}: endpoint not found")
            continue
        if {by_id[a]["type"], by_id[b]["type"]} - {"feature", "task"}:
            errors.append(f"{label}: dependencies link features or tasks only")
            continue
        if a == b:
            errors.append(f"{label}: self dependency")
            continue
        if a.startswith(b + "-") or b.startswith(a + "-"):
            errors.append(f"{label}: a task cannot depend on its own feature (or the reverse)")
            continue
        if kind not in EDGE_KINDS:
            errors.append(f"{label}: kind must be one of {sorted(EDGE_KINDS)}")
        if (a, b) in seen:
            errors.append(f"{label}: duplicate edge")
            continue
        seen.add((a, b))
        succ.setdefault(a, set()).add(b)
    cycle = find_cycle(set(by_id), succ)
    if cycle:
        errors.append("dependency cycle: " + " -> ".join(cycle))

    validate_stories(data, by_id, features, errors, warnings)

    return errors, warnings, {"by_id": by_id, "features": features, "edges": sorted(seen), "cycle": cycle}


def validate_stories(data, by_id, features, errors, warnings):
    """Business rules and user stories (optional sections of pwdev-roadmap/1)."""
    rules = data.get("rules")
    stories = data.get("stories")
    rule_ids = set()
    if rules is not None:
        for i, rule in enumerate(rules):
            rid = rule.get("id")
            if not rid or not RULE_ID.match(rid):
                errors.append(f"rules[{i}]: id must look like RN-01")
                continue
            if rid in rule_ids:
                errors.append(f"{rid}: duplicate rule id")
            rule_ids.add(rid)
            for field in ("title", "rule"):
                if not rule.get(field):
                    errors.append(f"{rid}: missing {field}")
            if not rule.get("example"):
                warnings.append(f"{rid}: rule without a concrete example")
    if stories is None:
        if features:
            warnings.append("no stories: run prd-stories to evolve each feature with user stories")
        return
    seen, applied_rules, per_feature = set(), set(), {}
    for i, story in enumerate(stories):
        sid = story.get("id")
        if not sid or not STORY_ID.match(sid):
            errors.append(f"stories[{i}]: id must look like US-01")
            continue
        if sid in seen:
            errors.append(f"{sid}: duplicate story id")
            continue
        seen.add(sid)
        feature = story.get("feature")
        if feature not in by_id or by_id[feature]["type"] != "feature":
            errors.append(f"{sid}: feature {feature!r} not found")
        else:
            per_feature.setdefault(feature, []).append(sid)
        persona = (story.get("persona") or "").strip()
        if not persona:
            errors.append(f"{sid}: missing persona")
        elif persona.lower() in SYSTEM_PERSONAS:
            errors.append(f"{sid}: persona {persona!r} is a system; name the person who benefits")
        elif persona.lower() in GENERIC_PERSONAS:
            warnings.append(f"{sid}: generic persona {persona!r}; use a persona named in the PRD")
        for field in ("title", "action", "value"):
            if not (story.get(field) or "").strip():
                errors.append(f"{sid}: missing {field}")
        action, value = (story.get("action") or "").strip().lower(), (story.get("value") or "").strip().lower()
        if action and value and (value == action or value in action):
            errors.append(f"{sid}: value clause repeats the action")
        if story.get("priority") not in PRIORITIES:
            errors.append(f"{sid}: priority must be one of {sorted(PRIORITIES)}")
        status = story.get("status")
        if status not in STORY_STATUS:
            errors.append(f"{sid}: status must be draft or ready")
        for rid in story.get("rules") or []:
            if rid not in rule_ids:
                errors.append(f"{sid}: rule {rid} is not in rules[] (add it to the PRD Business Rules first)")
            applied_rules.add(rid)
        acceptance = story.get("acceptance") or []
        ca_ids, paths, ca_rules = set(), set(), set()
        for j, ca in enumerate(acceptance):
            cid = ca.get("id")
            label = f"{sid}/{cid or f'acceptance[{j}]'}"
            if not cid or not CA_ID.match(cid):
                errors.append(f"{label}: id must look like CA-01")
            elif cid in ca_ids:
                errors.append(f"{label}: duplicate CA id")
            ca_ids.add(cid)
            if ca.get("path") not in CA_PATHS:
                errors.append(f"{label}: path must be one of {sorted(CA_PATHS)}")
            paths.add(ca.get("path"))
            text = ca.get("text") or ""
            if not text.strip():
                errors.append(f"{label}: empty text")
            if ca.get("type") not in CA_TYPES:
                errors.append(f"{label}: type must be gherkin or check")
            elif ca["type"] == "gherkin":
                missing = [k for k, rx in GHERKIN.items() if not rx.search(text)]
                if missing:
                    errors.append(f"{label}: Gherkin needs {'/'.join(missing)} (Dado/Quando/Então or Given/When/Then)")
            if VAGUE.search(text):
                warnings.append(f"{label}: vague term {VAGUE.search(text).group(0)!r}; make it measurable")
            for rid in ca.get("rules") or []:
                if rid not in (story.get("rules") or []):
                    errors.append(f"{label}: cites {rid} but the story does not list it in rules")
                ca_rules.add(rid)
        if len(acceptance) > MAX_CA:
            errors.append(f"{sid}: {len(acceptance)} CA, split the story (max {MAX_CA})")
        if status == "ready":
            if len(acceptance) < MIN_READY_CA:
                errors.append(f"{sid}: ready needs at least {MIN_READY_CA} CA (has {len(acceptance)})")
            if "happy" not in paths:
                errors.append(f"{sid}: ready needs a happy-path CA")
            if not paths & {"error", "edge"}:
                errors.append(f"{sid}: ready needs an error or edge CA")
            for rid in story.get("rules") or []:
                if rid not in ca_rules:
                    errors.append(f"{sid}: {rid} is listed but no CA verifies it")
        elif not acceptance:
            errors.append(f"{sid}: a draft needs at least one CA")
        for dep in story.get("depends_on") or []:
            if dep == sid or not STORY_ID.match(str(dep)):
                errors.append(f"{sid}: invalid dependency {dep!r}")
    for sid, story in ((s.get("id"), s) for s in stories):
        for dep in story.get("depends_on") or []:
            if STORY_ID.match(str(dep)) and dep not in seen:
                errors.append(f"{sid}: depends on unknown story {dep}")
    for fid in features:
        count = len(per_feature.get(fid, []))
        if count == 0:
            errors.append(f"{fid}: feature without user stories")
        elif count > MAX_STORIES_PER_FEATURE:
            errors.append(f"{fid}: {count} stories, split the feature (max {MAX_STORIES_PER_FEATURE})")
    for rid in sorted(rule_ids - applied_rules):
        warnings.append(f"{rid}: business rule not applied by any story")


def slugify(text):
    text = unicodedata.normalize("NFKD", text).encode("ascii", "ignore").decode()
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")[:48] or "story"


def story_filename(story):
    return f"{story['id']}-{slugify(story.get('title', ''))}.md"


def render_story(story, data, by_id):
    pt = (data.get("meta") or {}).get("language", "en").lower().startswith("pt")
    rules = {r["id"]: r for r in data.get("rules") or []}
    feature = by_id.get(story["feature"], {})
    lines = [GENERATED_MARK, "",
             f"# {story['id']} — {story['title']}", "",
             f"- Feature: {story['feature']} {feature.get('title', '')}",
             f"- {'Prioridade' if pt else 'Priority'}: {story.get('priority', '')} · Status: {story.get('status', '')}",
             f"- {'Depende de' if pt else 'Depends on'}: {', '.join(story.get('depends_on') or []) or ('nenhuma' if pt else 'none')}",
             ""]
    if pt:
        lines.append(f"Como **{story['persona']}**, quero **{story['action']}**, para **{story['value']}**.")
    else:
        lines.append(f"As a **{story['persona']}**, I want **{story['action']}**, so that **{story['value']}**.")
    lines += ["", f"## {'Critérios de aceite' if pt else 'Acceptance criteria'}", ""]
    for ca in story.get("acceptance") or []:
        tag = f"{ca['id']} ({ca.get('path', '')}" + (f", {', '.join(ca['rules'])}" if ca.get("rules") else "") + ")"
        if ca.get("type") == "gherkin":
            lines += [f"- [ ] **{tag}**", "", "  ```gherkin"] + [f"  {l}" for l in ca["text"].splitlines()] + ["  ```", ""]
        else:
            lines.append(f"- [ ] **{tag}** {ca['text']}")
    while lines and lines[-1] == "":
        lines.pop()
    if story.get("rules"):
        lines += ["", f"## {'Regras de negócio' if pt else 'Business rules'}", ""]
        for rid in story["rules"]:
            rule = rules.get(rid, {})
            lines.append(f"- **{rid} — {rule.get('title', '')}:** {rule.get('rule', '')}"
                         + (f" _{'Ex.' if pt else 'E.g.'}: {rule['example']}_" if rule.get("example") else ""))
    if story.get("out_of_scope"):
        lines += ["", f"## {'Fora de escopo' if pt else 'Out of scope'}", "", story["out_of_scope"]]
    return "\n".join(lines).rstrip() + "\n"


def render_story_files(data, ctx, root: Path):
    """Write stories/US-*.md and STORIES.md; remove generated files of stories that no longer exist."""
    stories = data.get("stories")
    if stories is None:
        return
    pt = (data.get("meta") or {}).get("language", "en").lower().startswith("pt")
    folder = root / "stories"
    folder.mkdir(exist_ok=True)
    wanted = set()
    for story in stories:
        name = story_filename(story)
        wanted.add(name)
        (folder / name).write_text(render_story(story, data, ctx["by_id"]), encoding="utf-8")
    for old in folder.glob("US-*.md"):
        if old.name not in wanted and GENERATED_MARK in old.read_text(encoding="utf-8"):
            old.unlink()
    by_feature = {}
    for story in stories:
        by_feature.setdefault(story["feature"], []).append(story)
    ready = sum(1 for s in stories if s.get("status") == "ready")
    lines = [GENERATED_MARK, "", f"# {'Histórias de usuário' if pt else 'User stories'}", "",
             f"{ready}/{len(stories)} ready.", ""]
    head = "| US | Persona | Status | CA | RN |"
    for fid in sorted(ctx["features"]):
        lines += [f"## {fid} {ctx['by_id'][fid]['title']}", "", head, "|---|---|---|---|---|"]
        for s in by_feature.get(fid, []):
            lines.append(f"| [{s['id']} {s['title']}](stories/{story_filename(s)}) | {s['persona']} | "
                         f"{s.get('status', '')} | {len(s.get('acceptance') or [])} | {', '.join(s.get('rules') or []) or '—'} |")
        lines.append("")
    if data.get("rules"):
        used = {}
        for s in stories:
            for rid in s.get("rules") or []:
                used.setdefault(rid, []).append(s["id"])
        lines += [f"## {'Regras de negócio' if pt else 'Business rules'}", "",
                  "| RN | " + ("Regra" if pt else "Rule") + " | " + ("Histórias" if pt else "Stories") + " |", "|---|---|---|"]
        for r in data["rules"]:
            lines.append(f"| {r['id']} {r.get('title', '')} | {r.get('rule', '')} | {', '.join(used.get(r['id'], [])) or '—'} |")
    (root / "STORIES.md").write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8")


def feature_of(nid):
    return nid.split("-T")[0] if re.search(r"-T\d{2}$", nid) else nid


def plan(ctx):
    """Waves and critical path over features; task edges lift to their features."""
    by_id, features = ctx["by_id"], sorted(ctx["features"])
    preds = {f: set() for f in features}
    lifted = set()
    for a, b in ctx["edges"]:
        fa, fb = feature_of(a), feature_of(b)
        if fa != fb:
            preds[fb].add(fa)
            lifted.add((fa, fb))
    wave = {}

    def level(f):
        if f not in wave:
            wave[f] = 1 + max((level(p) for p in preds[f]), default=0)
        return wave[f]

    for f in features:
        level(f)
    weight = {f: ESTIMATES.get(by_id[f].get("estimate"), 1) for f in features}
    best, prev = {}, {}
    for f in sorted(features, key=lambda x: (wave[x], x)):
        base = max(preds[f], key=lambda p: (best[p], p), default=None)
        best[f] = weight[f] + (best[base] if base else 0)
        prev[f] = base
    end = max(features, key=lambda f: (best[f], f)) if features else None
    path = []
    while end:
        path.append(end)
        end = prev[end]
    path.reverse()
    waves = {}
    for f in features:
        waves.setdefault(wave[f], []).append(f)
    return {
        "waves": [sorted(waves[k]) for k in sorted(waves)],
        "wave_of": wave,
        "critical_path": path,
        "critical_weight": best[path[-1]] if path else 0,
        "feature_edges": sorted(lifted),
    }


def mermaid_id(nid):
    return nid.replace("-", "_")


def render(data, ctx, result):
    lang = (data.get("meta") or {}).get("language", "en")
    t = TEXT["pt-BR" if lang.lower().startswith("pt") else "en"]
    by_id = ctx["by_id"]
    critical = set(result["critical_path"])
    out = [f"# {t['title']}", "", f"> {t['generated']}", "", f"## {t['graph']}", "", "```mermaid", "flowchart LR"]
    for f in sorted(ctx["features"]):
        title = by_id[f]["title"].replace('"', "'")
        out.append(f'  {mermaid_id(f)}["{f}<br/>{title}"]')
    for a, b in result["feature_edges"]:
        out.append(f"  {mermaid_id(a)} --> {mermaid_id(b)}")
    if critical:
        out.append("  classDef critical stroke-width:3px")
        out.append("  class " + ",".join(mermaid_id(f) for f in result["critical_path"]) + " critical")
    out += ["```", "", f"## {t['edges']}", ""]
    if ctx["edges"]:
        out += [t["edge_head"], "|---|---|---|"]
        kinds = {(e["from"], e["to"]): e.get("kind", "") for e in data.get("edges") or []}
        for a, b in ctx["edges"]:
            out.append(f"| {a} {by_id[a]['title']} | {b} {by_id[b]['title']} | {kinds.get((a, b), '')} |")
    else:
        out.append(t["no_edges"])
    out += ["", f"## {t['waves']}", "", t["waves_note"], ""]
    for i, wave in enumerate(result["waves"], 1):
        out.append(f"- **{t['wave']} {i}:** " + ", ".join(f"{f} {by_id[f]['title']}" for f in wave))
    out += ["", f"## {t['critical']}", "", t["critical_note"], ""]
    out.append(" → ".join(result["critical_path"]) + f" ({t['weight']} {result['critical_weight']})")
    return "\n".join(out) + "\n"


def story_counts(data):
    stories = data.get("stories") or []
    ready = sum(1 for s in stories if s.get("status") == "ready")
    return {"total": len(stories), "ready": ready, "draft": len(stories) - ready,
            "rules": len(data.get("rules") or [])}


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("roadmap")
    parser.add_argument("--no-write", action="store_true", help="validate only; do not write DEPENDENCIES.md")
    parser.add_argument("--json", action="store_true", help="print the result as JSON")
    args = parser.parse_args(argv)
    path = Path(args.roadmap)
    data = load(path)
    errors, warnings, ctx = validate(data, path.parent)
    result = plan(ctx) if not errors else None
    if result and not args.no_write:
        (path.parent / "DEPENDENCIES.md").write_text(render(data, ctx, result), encoding="utf-8")
        render_story_files(data, ctx, path.parent)
    counts = {}
    for node in (ctx.get("by_id") or {}).values():
        counts[node["type"]] = counts.get(node["type"], 0) + 1
    if args.json:
        payload = {"status": "FAIL" if errors else "PASS", "errors": errors, "warnings": warnings, "counts": counts,
                   "stories": story_counts(data)}
        if result:
            payload.update(waves=result["waves"], critical_path=result["critical_path"],
                           critical_weight=result["critical_weight"])
        print(json.dumps(payload, ensure_ascii=False, indent=2))
    else:
        print("FAIL" if errors else "PASS")
        for e in errors:
            print(f"- {e}")
        for w in warnings:
            print(f"- warning: {w}")
        if result:
            print(f"counts: {counts.get('phase', 0)} phases | {counts.get('epic', 0)} epics | "
                  f"{counts.get('feature', 0)} features | {counts.get('task', 0)} tasks")
            print(f"waves: {len(result['waves'])} | critical path: {' -> '.join(result['critical_path'])}")
            sc = story_counts(data)
            print(f"stories: {sc['total']} ({sc['ready']} ready, {sc['draft']} draft) | rules: {sc['rules']}")
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
