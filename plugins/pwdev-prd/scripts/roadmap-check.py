ID_PATTERNS = {
    "phase": re.compile(r"^F\d{2}$"),
    "epic": re.compile(r"^F\d{2}-E\d{2}$"),
    "feature": re.compile(r"^F\d{2}-E\d{2}-FT\d{2}$"),
    "task": re.compile(r"^F\d{2}-E\d{2}-FT\d{2}-T\d{2}$"),
}
PARENT_TYPE = {"phase": None, "epic": "phase", "feature": "epic", "task": "feature"}
PRIORITIES = {"must", "should", "could", "wont"}
ESTIMATES = {"S": 1, "M": 2, "L": 3}
EDGE_KINDS = {"technical", "data", "external", "decision"}
MAX_TASKS_PER_FEATURE = 8
MAX_FEATURES_PER_EPIC = 8
MAX_FEATURES = 50
STORY_ID = re.compile(r"^US-\d{2,3}$")
RULE_ID = re.compile(r"^RN-\d{2,3}$")
CA_ID = re.compile(r"^CA-\d{2}$")
STORY_STATUS = {"draft", "ready"}
CA_PATHS = {"happy", "error", "edge"}
CA_TYPES = {"gherkin", "check"}
SYSTEM_PERSONAS = {"sistema", "o sistema", "system", "the system", "sistemas", "backend", "api"}
GENERIC_PERSONAS = {"usuário", "usuario", "user", "o usuário", "the user"}
VAGUE = re.compile(r"\b(rápid[oa]s?|fácil|fáceis|intuitiv[oa]s?|amigável|simples|fast|quick(?:ly)?|easy|intuitive|user[- ]friendly|seamless)\b", re.I)
GHERKIN = {"given": re.compile(r"^\s*(Dado|Given)\b", re.M | re.I),
           "when": re.compile(r"^\s*(Quando|When)\b", re.M | re.I),
           "then": re.compile(r"^\s*(Então|Entao|Then)\b", re.M | re.I)}
MIN_READY_CA, MAX_CA = 3, 8
MAX_STORIES_PER_FEATURE = 5
GENERATED_MARK = "<!-- generated by roadmap-check.py from roadmap.json: edit the story through prd-stories -->"

